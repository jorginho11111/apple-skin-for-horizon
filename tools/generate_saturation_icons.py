#!/usr/bin/env python3
"""Extract AppleSkin's four yellow saturation outlines into Rust pixel runs.

Only the original, pinned 4-bit indexed PNG is supported. The decoder uses the
Python standard library so CI needs no image-processing dependency. The PNG
is kept under third_party/, not assets/: an hmod without registries capability
must not ship a resource pack.
"""
from __future__ import annotations

import hashlib
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/appleskin/icons.png"
OUTPUT = ROOT / "src/saturation_icons.rs"
REVISION = "66fcdb8b12820c9b1cf3147abfdcf5530559f62b"
SOURCE_SHA256 = "6301a0b572f0e4bf84b5ac82ee83352e2e6f953397f8ab487c6a5268fac9bd3d"


def paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def rgba_rows(data: bytes) -> tuple[int, int, list[bytes]]:
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos = 8
    header = None
    palette = b""
    transparency = b""
    compressed = bytearray()
    while pos + 12 <= len(data):
        size, kind = struct.unpack_from(">I4s", data, pos)
        end = pos + 8 + size
        if end + 4 > len(data):
            raise ValueError("truncated PNG chunk")
        payload = data[pos + 8 : end]
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", payload)
        elif kind == b"PLTE":
            palette = payload
        elif kind == b"tRNS":
            transparency = payload
        elif kind == b"IDAT":
            compressed.extend(payload)
        pos = end + 4
    if header is None:
        raise ValueError("missing PNG header")
    width, height, depth, color, compression, filtering, interlace = header
    if (depth, color, compression, filtering, interlace) != (4, 3, 0, 0, 0):
        raise ValueError("expected the original non-interlaced, 4-bit indexed PNG")
    if not palette or len(palette) % 3 or len(palette) > 768:
        raise ValueError("invalid PNG palette")
    raw = zlib.decompress(compressed)
    stride = (width * depth + 7) // 8
    if len(raw) != height * (stride + 1):
        raise ValueError("unexpected decoded PNG size")
    rows = []
    previous = bytes(stride)
    for y in range(height):
        start = y * (stride + 1)
        method = raw[start]
        if method > 4:
            raise ValueError("invalid PNG filter")
        row = bytearray(raw[start + 1 : start + 1 + stride])
        for i in range(stride):
            left = row[i - 1] if i >= 1 else 0
            up = previous[i]
            upper_left = previous[i - 1] if i >= 1 else 0
            predictor = (
                0,
                left,
                up,
                (left + up) // 2,
                paeth(left, up, upper_left),
            )[method]
            row[i] = (row[i] + predictor) & 255
        previous = bytes(row)
        rgba = bytearray()
        for x in range(width):
            index = (row[x // 2] >> (4 if x % 2 == 0 else 0)) & 15
            if index * 3 + 3 > len(palette):
                raise ValueError("PNG palette index out of range")
            rgba.extend(palette[index * 3 : index * 3 + 3])
            rgba.append(transparency[index] if index < len(transparency) else 255)
        rows.append(bytes(rgba))
    return width, height, rows


def icon_runs() -> list[list[tuple[int, int, int, int]]]:
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError("pinned AppleSkin icons.png changed")
    width, height, rows = rgba_rows(data)
    if (width, height) != (256, 256):
        raise ValueError("unexpected AppleSkin texture size")
    variants = []
    for variant in range(4):
        runs = []
        for y in range(9):
            x = 0
            while x < 9:
                offset = (variant * 9 + x) * 4
                pixel = tuple(rows[y][offset : offset + 4])
                if pixel[3] == 0:
                    x += 1
                    continue
                if pixel[3] != 255:
                    raise ValueError("expected binary alpha in the pinned outlines")
                start = x
                while x < 9:
                    offset = (variant * 9 + x) * 4
                    if tuple(rows[y][offset : offset + 4]) != pixel:
                        break
                    x += 1
                rgb = (pixel[0] << 16) | (pixel[1] << 8) | pixel[2]
                runs.append((y, start, x - start, rgb))
        variants.append(runs)
    return variants


def render(variants: list[list[tuple[int, int, int, int]]]) -> str:
    lines = [
        "// Generated by tools/generate_saturation_icons.py. Do not edit by hand.",
        "// Source: squeek502/AppleSkin, resources/assets/appleskin/textures/icons.png.",
        f"// Revision: {REVISION} (Unlicense).",
        f"// PNG SHA-256: {SOURCE_SHA256}",
        "// Order: quarter, half, three-quarter, full; same thresholds as upstream.",
        "",
        "/// One horizontal run of opaque pixels in a 9x9 saturation outline.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct PixelRun {",
        "    pub x: u8,",
        "    pub y: u8,",
        "    pub w: u8,",
        "    pub rgb: u32,",
        "}",
        "",
        "// Keep the generated table compact and stable under cargo fmt.",
        "#[rustfmt::skip]",
        "pub const ICONS: [&[PixelRun]; 4] = [",
    ]
    for runs in variants:
        lines.append("    &[")
        for y, x, width, rgb in runs:
            lines.append(
                f"        PixelRun {{ x: {x}, y: {y}, w: {width}, rgb: 0x{rgb:06X} }},"
            )
        lines.append("    ],")
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> None:
    OUTPUT.write_text(render(icon_runs()), encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
